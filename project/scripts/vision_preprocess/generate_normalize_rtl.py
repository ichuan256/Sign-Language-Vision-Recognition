"""Generate the finite uint8 / 255 binary32 ROM using exact integer arithmetic.

The simulation oracle is independently generated by NumPy float32 division in
 generate_vectors.py. No floating point operation is used to produce this RTL.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
TARGET = ROOT / 'project/fpga/rtl/vision_preprocess/rgb888_axis_fp32_normalize.v'


def normalized_bits(value):
    """IEEE754 binary32 round-to-nearest, ties-to-even for exact value/255."""
    if not 0 <= value <= 255:
        raise ValueError('Expected a uint8 value')
    if value == 0:
        return 0
    exponent = 0
    while (value << -exponent) < 255:
        exponent -= 1
    significand, remainder = divmod(value << (23 - exponent), 255)
    if 2 * remainder > 255 or (2 * remainder == 255 and significand & 1):
        significand += 1
    if significand == 1 << 24:
        significand >>= 1
        exponent += 1
    return ((exponent + 127) << 23) | (significand - (1 << 23))


def render():
    rows = '\n'.join(f"            8'd{i}: normalize=30'h{normalized_bits(i):08x};" for i in range(256))
    return '''`timescale 1ns/1ps
// Generated by project/scripts/vision_preprocess/generate_normalize_rtl.py.
// Exact uint8 / 255 rounded to IEEE754 binary32, nearest/even; no FP IP.
// Each accepted RGB pixel emits three full words, R then G then B. A held
// output and all metadata are stable until handshake. Reset is coordinated
// with the AXIS consumer, as for the parent peripheral.
module rgb888_axis_fp32_normalize (
    input wire clk, input wire reset_n,
    input wire [23:0] s_axis_tdata,
    input wire s_axis_tvalid, output wire s_axis_tready,
    input wire s_axis_tuser, input wire s_axis_tlast,
    output wire [31:0] m_axis_tdata, output wire [3:0] m_axis_tkeep,
    output wire m_axis_tvalid, input wire m_axis_tready,
    output wire m_axis_tuser, output wire m_axis_tlast
);
    reg [23:0] pixel;
    reg pixel_user, pixel_last, occupied;
    reg [1:0] channel;
    wire [7:0] sample = channel==0 ? pixel[7:0] :
                        channel==1 ? pixel[15:8] : pixel[23:16];
    function [29:0] normalize;
        input [7:0] value;
        begin
            case (value)
''' + rows + '''
                default: normalize=30'h00000000;
            endcase
        end
    endfunction
    assign s_axis_tready = !occupied || (channel==2 && m_axis_tready);
    // [0,1] has sign=0 and exponent MSB=0; drive both bits explicitly.
    assign m_axis_tdata = {2'b00, normalize(sample)};
    assign m_axis_tkeep = 4'b1111;
    assign m_axis_tvalid = occupied;
    assign m_axis_tuser = pixel_user && channel==0;
    assign m_axis_tlast = pixel_last && channel==2;
    always @(posedge clk) begin
        if (!reset_n) begin
            pixel<=0; pixel_user<=0; pixel_last<=0; occupied<=0; channel<=0;
        end else begin
            if (occupied && m_axis_tready) begin
                if (channel==2) begin occupied<=0; channel<=0; end
                else channel<=channel+1'b1;
            end
            if (s_axis_tvalid && s_axis_tready) begin
                pixel<=s_axis_tdata; pixel_user<=s_axis_tuser;
                pixel_last<=s_axis_tlast; occupied<=1; channel<=0;
            end
        end
    end
endmodule
'''


if __name__ == '__main__':
    TARGET.write_text(render(), encoding='ascii')
    print(TARGET)
