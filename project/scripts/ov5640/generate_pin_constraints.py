"""Validate wiring JSON and reproduce physical-only XDC for camera tops.
No sensor timing delays are guessed; legacy W6 lacks the camera ports.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
MAP = ROOT / 'project/analysis/ov5640_stereo_20261026/physical_pin_map_20261027.json'
XDC = ROOT / 'project/fpga/xdc/ov5640_stereo_pins.xdc'
LOADER = ROOT / 'project/fpga/scripts/load_ov5640_pins.tcl'
# TUL v1.1 table 22, checked against frozen PYNQ v3.0.1 base.xdc.
RPI = {3:'W18',5:'W19',7:'Y18',8:'V6',10:'Y6',11:'U7',12:'C20',
       13:'V7',15:'U8',16:'W6',18:'Y7',19:'V8',21:'V10',22:'F20',
       23:'W10',24:'F19',26:'U19',27:'Y16',28:'Y17',29:'Y19',
       31:'U18',32:'B20',33:'W8',35:'Y8',36:'B19',37:'W9',38:'A20',40:'Y9'}
SIGNALS = ['VSYNC','SCL','HREF','SDA','RESET'] + [f'D{i}' for i in range(8)] + ['PCLK','PWDN']

def expected_port(camera: str, signal: str) -> str:
    prefix = camera.lower()
    if signal.startswith('D') and signal[1:].isdigit():
        return f'{prefix}_data[{signal[1:]}]'
    return f'{prefix}_' + ('reset_n' if signal == 'RESET' else signal.lower())

def validate(mapping: dict) -> list[dict]:
    if mapping.get('device') != 'xc7z020clg400-1':
        raise ValueError('Unexpected FPGA part')
    rows = mapping.get('signals', [])
    if len(rows) != 30:
        raise ValueError('Exactly 30 camera signals required')
    keys, ports, pads, headers, module_pins = set(), set(), set(), set(), set()
    for row in rows:
        camera, signal = row['camera'], row['signal']
        if camera not in ('OV1','OV2') or signal not in SIGNALS:
            raise ValueError('Unknown camera or signal')
        key = (camera, signal)
        port, pad = row['rtl_port'], row['package_pin']
        if key in keys or port in ports or pad in pads:
            raise ValueError('Duplicate signal, RTL port or package pin')
        keys.add(key); ports.add(port); pads.add(pad)
        if port != expected_port(camera, signal):
            raise ValueError('RTL port does not match camera/signal')
        if row['io_standard'] != 'LVCMOS33':
            raise ValueError('Unexpected IO standard')
        direction = ('bidirectional_open_drain' if signal in ('SCL','SDA')
                     else 'fpga_to_camera' if signal in ('RESET','PWDN')
                     else 'camera_to_fpga')
        if row['direction'] != direction:
            raise ValueError('Incorrect signal direction')
        pin1 = dict(zip(SIGNALS, [5,6,7,8,9,*range(10,18),18,19]))
        pin2 = dict(zip(SIGNALS, [21,22,23,24,25,*range(26,34),34,20]))
        if row['camera_connector'] != 'P1' or row['camera_pin'] != (pin1 if camera == 'OV1' else pin2)[signal]:
            raise ValueError('Incorrect camera P1 pin')
        if row['camera_pin'] in module_pins:
            raise ValueError('Duplicate camera P1 pin')
        module_pins.add(row['camera_pin'])
        header = (row['board_connector'], row['board_pin'])
        if header in headers:
            raise ValueError('Duplicate board connector pin')
        headers.add(header)
        if signal == 'PWDN':
            expected = ('R16', 7, 'D6') if camera == 'OV1' else ('U17', 8, 'D7')
            if (pad, row['board_pin'], row.get('board_label')) != expected or row['board_connector'] != 'Arduino J4':
                raise ValueError('Incorrect Arduino PWDN mapping')
        elif row['board_connector'] != 'Raspberry Pi' or RPI.get(row['board_pin']) != pad:
            raise ValueError('Board header/package mapping disagrees with v1.1')
        if signal == 'PCLK':
            expected = ('Y9','IO_L14P_T2_SRCC_13') if camera == 'OV1' else ('U7','IO_L11P_T1_SRCC_13')
            if (pad, row.get('clock_pin_function')) != expected:
                raise ValueError('PCLK requires verified clock-capable P-side pin')
        elif 'clock_pin_function' in row:
            raise ValueError('Stale clock function on non-clock signal')
    if keys != {(camera,signal) for camera in ('OV1','OV2') for signal in SIGNALS}:
        raise ValueError('Incomplete camera signal set')
    return rows

def render(mapping: dict) -> str:
    rows = validate(mapping)
    lines = [
        '# Generated by project/scripts/ov5640/generate_pin_constraints.py; do not edit.',
        '# Native XDC: load through scripts/load_ov5640_pins.tcl for preflight checks.',
        '# Physical pin assignments only; no unverified sensor timing delays.',
        '# SCCB uses external 2.8V pullups; no FPGA pullups or drive-high.',
    ]
    for row in rows:
        lines.append('set_property -dict {PACKAGE_PIN ' + row['package_pin'] +
                     ' IOSTANDARD LVCMOS33} [get_ports {' + row['rtl_port'] + '}]')
    return chr(10).join(lines) + chr(10)

def render_loader(mapping: dict) -> str:
    rows = validate(mapping)
    lines = [
        '# Generated by project/scripts/ov5640/generate_pin_constraints.py; do not edit.',
        '# Canonical map: physical_pin_map_20261027.json; PYNQ-Z2 / xc7z020clg400-1.',
        '# Guarded loader for native XDC. Legacy W6 lacks these camera ports.',
        '# Board timing/electrical acceptance is separate; SCCB has 2.8V pullups.',
        '# Do not add FPGA pullups or drive SCCB high.',
        'set ov5640_pin_map {',
    ]
    for r in rows:
        lines.append('    {' + r['rtl_port'] + ' ' + r['package_pin'] + '}')
    lines += [
        '}',
        '# Validate all ports and conflicts BEFORE assigning any camera pin.',
        'foreach ov5640_entry $ov5640_pin_map {',
        '    lassign $ov5640_entry ov5640_name ov5640_pad',
        '    set ov5640_port [get_ports -quiet -filter [format {NAME == "%s"} $ov5640_name]]',
        '    if {[llength $ov5640_port] != 1} {error "Camera XDC requires port $ov5640_name"}',
        '}',
        'foreach ov5640_other [get_ports -quiet *] {',
        '    set ov5640_assigned [get_property PACKAGE_PIN $ov5640_other]',
        '    foreach ov5640_entry $ov5640_pin_map {',
        '        lassign $ov5640_entry ov5640_name ov5640_pad',
        '        if {$ov5640_assigned eq $ov5640_pad && [get_property NAME $ov5640_other] ne $ov5640_name} {',
        '            error "Camera pin $ov5640_pad conflicts with port $ov5640_other"',
        '        }',
        '    }',
        '}',
        'read_xdc [file normalize [file join [file dirname [info script]] ../xdc/ov5640_stereo_pins.xdc]]',
        'unset ov5640_pin_map ov5640_entry ov5640_name ov5640_pad ov5640_port ov5640_other ov5640_assigned',
    ]
    return chr(10).join(lines) + chr(10)

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--map', type=Path, default=MAP)
    parser.add_argument('--output', type=Path, default=XDC)
    parser.add_argument('--loader-output', type=Path, default=LOADER)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        mapping = json.loads(args.map.read_text(encoding='utf-8-sig'))
        outputs = [(args.output,render(mapping)),(args.loader_output,render_loader(mapping))]
        if args.check:
            for path, expected in outputs:
                if not path.exists() or path.read_text(encoding='utf-8') != expected:
                    raise ValueError(f'Generated constraint artifact is missing or stale: {path}')
        else:
            for path, expected in outputs:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(expected, encoding='utf-8', newline=chr(10))
    except (ValueError, KeyError, OSError, TypeError) as exc:
        parser.exit(1, f'PIN_MAP_FAIL: {exc}' + chr(10))
    print('PIN_MAP_PASS: 30 unique signals; header, PCLK and XDC consistent')
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
